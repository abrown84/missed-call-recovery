#!/usr/bin/env node
/**
 * Build NANP area-code → IANA zone map from Google libphonenumber map_data.txt.
 *
 * Usage:
 *   node scripts/generate-nanp-zones.mjs           # write snapshot + data module
 *   node scripts/generate-nanp-zones.mjs --check   # regenerate to temp; diff snapshot (CI)
 *
 * Conservative quiet-hours: for each NPA, UNION all zones under any longer
 * prefix (1NXX…). Callers with only an area code must satisfy every zone.
 */
import {
  readFileSync,
  writeFileSync,
  mkdirSync,
  mkdtempSync,
  rmSync,
} from 'fs';
import { join, dirname, resolve as resolvePath } from 'path';
import { fileURLToPath } from 'url';
import { tmpdir } from 'os';
import { createHash } from 'crypto';
import { execFileSync } from 'child_process';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const MAP_DATA = join(ROOT, 'third_party/libphonenumber/map_data.txt');
const SNAPSHOT = join(ROOT, 'test/fixtures/nanp-area-code-zones.json');
const DATA_TS = join(ROOT, 'src/services/quiet-hours-zones-data.ts');
const META = join(ROOT, 'third_party/libphonenumber/SOURCE.md');

/** Valid NANP NPA: NXX with N=2–9. */
function isNpa(ac) {
  return /^[2-9]\d{2}$/.test(ac);
}

/**
 * Aggregate prefix→zones from map_data into NPA→sorted unique zones.
 * Root `1|…` (no NPA) is ignored — only prefixes `1` + ≥3 digits contribute.
 */
export function buildNpaZoneMap(mapDataText) {
  /** @type {Map<string, Set<string>>} */
  const byNpa = new Map();

  for (const raw of mapDataText.split('\n')) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const bar = line.indexOf('|');
    if (bar < 0) continue;
    const prefix = line.slice(0, bar);
    const zonesPart = line.slice(bar + 1);
    if (!prefix.startsWith('1') || prefix.length < 4) continue;
    const npa = prefix.slice(1, 4);
    if (!isNpa(npa)) continue;
    const zones = zonesPart.split('&').map((z) => z.trim()).filter(Boolean);
    if (!byNpa.has(npa)) byNpa.set(npa, new Set());
    const set = byNpa.get(npa);
    for (const z of zones) set.add(z);
  }

  /** @type {Record<string, string[]>} */
  const out = {};
  for (const npa of [...byNpa.keys()].sort()) {
    out[npa] = [...byNpa.get(npa)].sort();
  }
  return out;
}

function mapDataSha256(text) {
  return createHash('sha256').update(text).digest('hex');
}

function renderDataTs(map, meta) {
  const jsonLiteral = JSON.stringify(map, null, 2);
  return `/**
 * GENERATED FILE — do not edit by hand.
 *
 * Source: Google libphonenumber ${meta.tag} map_data.txt
 * Commit: ${meta.commit}
 * map_data sha256: ${meta.sha256}
 * Regenerated by: npm run generate:nanp-zones
 *
 * Scope: all NANP (country-code 1) NPAs in map_data — US, Canada, territories.
 * Canada is in scope for quiet-hours. Multi-zone NPAs list the UNION of zones
 * (conservative: every listed zone must be open).
 *
 * Why not under Stryker mutate: static ObjectLiteral explosion; golden snapshot
 * + \`npm run check:nanp-zones\` + zonesForAreaCode() cover regressions.
 */
export const AREA_CODE_ZONES: Record<string, string[]> = ${jsonLiteral};

/** Florida NPAs — TCPA end hour 20:00 (state rule; not from map_data). */
export const FL_AREA = new Set([
  '239', '305', '321', '352', '386', '407', '448', '561', '645', '656', '689',
  '727', '728', '754', '772', '786', '813', '850', '863', '904', '941', '954',
]);

/** Oklahoma NPAs — TCPA end hour 20:00 (state rule; not from map_data). */
export const OK_AREA = new Set(['405', '539', '572', '580', '918']);
`;
}

function parseSourceMeta() {
  const md = readFileSync(META, 'utf8');
  const tag = (md.match(/\*\*([vV][\d.]+)\*\*/) || [])[1] || 'unknown';
  const commit = (md.match(/`([0-9a-f]{40})`/) || [])[1] || 'unknown';
  return { tag, commit };
}

function writeOutputs(map, destSnapshot, destDataTs, meta) {
  mkdirSync(dirname(destSnapshot), { recursive: true });
  writeFileSync(destSnapshot, `${JSON.stringify(map, null, 2)}\n`, 'utf8');
  writeFileSync(destDataTs, renderDataTs(map, meta), 'utf8');
}

function main() {
  const checkOnly = process.argv.includes('--check');
  const mapText = readFileSync(MAP_DATA, 'utf8');
  const map = buildNpaZoneMap(mapText);
  const meta = {
    ...parseSourceMeta(),
    sha256: mapDataSha256(mapText),
  };

  if (checkOnly) {
    const dir = mkdtempSync(join(tmpdir(), 'nanp-zones-'));
    try {
      const snap = join(dir, 'nanp-area-code-zones.json');
      const dataTs = join(dir, 'quiet-hours-zones-data.ts');
      writeOutputs(map, snap, dataTs, meta);
      const committed = readFileSync(SNAPSHOT, 'utf8');
      const generated = readFileSync(snap, 'utf8');
      if (committed !== generated) {
        console.error(
          'FAIL: test/fixtures/nanp-area-code-zones.json is stale vs map_data.txt'
        );
        try {
          execFileSync('diff', ['-u', SNAPSHOT, snap], { stdio: 'inherit' });
        } catch {
          /* diff exits 1 on mismatch */
        }
        process.exit(1);
      }
      const committedTs = readFileSync(DATA_TS, 'utf8');
      const committedMap = JSON.parse(committed);
      if (JSON.stringify(committedMap) !== JSON.stringify(map)) {
        console.error('FAIL: committed snapshot JSON !== regenerated map');
        process.exit(1);
      }
      if (!committedTs.includes(meta.sha256)) {
        console.error(
          'FAIL: quiet-hours-zones-data.ts missing map_data sha256 — re-run generate:nanp-zones'
        );
        process.exit(1);
      }
      const m = committedTs.match(
        /export const AREA_CODE_ZONES: Record<string, string\[\]> = (\{\n[\s\S]*?\n\});/
      );
      if (!m) {
        console.error('FAIL: could not parse AREA_CODE_ZONES from data module');
        process.exit(1);
      }
      const embedded = JSON.parse(m[1]);
      if (JSON.stringify(embedded) !== JSON.stringify(map)) {
        console.error(
          'FAIL: quiet-hours-zones-data.ts AREA_CODE_ZONES !== regenerated map'
        );
        process.exit(1);
      }
      console.log(
        `OK nanp-zones: ${Object.keys(map).length} NPAs match snapshot (libphonenumber ${meta.tag})`
      );
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
    return;
  }

  writeOutputs(map, SNAPSHOT, DATA_TS, meta);
  console.log(
    `Wrote ${Object.keys(map).length} NPAs → ${SNAPSHOT} and ${DATA_TS}`
  );
}

const isMain =
  Boolean(process.argv[1]) &&
  resolvePath(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  main();
}
